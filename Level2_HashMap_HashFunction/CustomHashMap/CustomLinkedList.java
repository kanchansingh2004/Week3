package Level2_HashMap_HashFunction.CustomHashMap;

// CustomLinkedList class to create a linked list
public class CustomLinkedList {
    // Data and key to store the data and key of the node
    int data;
    int key;
    CustomLinkedList next;

    // Constructor to initialize the data and key of the node
    CustomLinkedList(int data, int key){
        this.data=data;
        this.key=key;
        this.next=null;
    }
}
